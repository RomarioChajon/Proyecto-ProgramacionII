    private void cargarDatosDesdeBD() {

        if (cargandoDatos) {
            return;
        }

        cargandoDatos = true;

        bmtNuevaSolicitud.setEnabled(false);
        btnAgregarEquipo.setEnabled(false);

        SwingWorker<Void, Void> worker =
                new SwingWorker<>() {

                    private List<Laboratorio> nuevosLaboratorios;
                    private List<Producto> nuevosProductos;
                    private Map<Integer, String> nuevasCategorias;

                    @Override
                    protected Void doInBackground()
                            throws Exception {

                        nuevosLaboratorios =
                                laboratorioRepository.listarActivos();

                        nuevosProductos =
                                productoRepository.listar();

                        nuevasCategorias =
                                consultarNombresCategorias();

                        return null;
                    }

                    @Override
                    protected void done() {

                        cargandoDatos = false;

                        bmtNuevaSolicitud.setEnabled(true);
                        btnAgregarEquipo.setEnabled(true);

                        try {

                            get();

                            laboratorios.clear();
                            laboratorios.addAll(
                                    nuevosLaboratorios
                            );

                            productos.clear();

                            for (Producto producto :
                                    nuevosProductos) {

                                productos.put(
                                        producto.getIdProducto(),
                                        producto
                                );
                            }

                            nombresCategorias.clear();
                            nombresCategorias.putAll(
                                    nuevasCategorias
                            );

                            cargarSedes();

                        } catch (Exception ex) {

                            mostrarError(
                                    "No fue posible cargar los datos "
                                            + "de SQL Server.",
                                    ex
                            );
                        }
                    }
                };

        worker.execute();
    }

    private Map<Integer, String> consultarNombresCategorias()
            throws SQLException {

        Map<Integer, String> resultado =
                new HashMap<>();

        String sql = """
                SELECT id_tipo_equipo, nombre
                FROM dbo.TipoEquipo
                """;

        try (Connection cn =
                     DatabaseConnection.getConnection();

             PreparedStatement ps =
                     cn.prepareStatement(sql);

             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {

                resultado.put(
                        rs.getInt("id_tipo_equipo"),
                        rs.getString("nombre")
                );
            }
        }

        return resultado;
    }

    private void cargarSedes() {

        actualizandoCombos = true;

        try {

            cmbSede.removeAllItems();

            TreeSet<String> sedes =
                    new TreeSet<>(
                            String.CASE_INSENSITIVE_ORDER
                    );

            for (Laboratorio laboratorio :
                    laboratorios) {

                String ubicacion =
                        laboratorio.getUbicacion();

                if (ubicacion != null
                        && !ubicacion.isBlank()) {

                    sedes.add(ubicacion.trim());
                }
            }

            for (String sede : sedes) {
                cmbSede.addItem(sede);
            }

            if (cmbSede.getItemCount() > 0) {
                cmbSede.setSelectedIndex(0);
            }

        } finally {

            actualizandoCombos = false;
        }

        actualizarLaboratorios();
    }

