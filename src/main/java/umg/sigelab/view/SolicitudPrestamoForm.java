    private void mostrarError(
            String mensaje,
            Exception ex
    ) {

        Throwable causa = ex;

        while (causa.getCause() != null) {
            causa = causa.getCause();
        }

        JOptionPane.showMessageDialog(
                this,
                mensaje + "\n\nDetalle: "
                        + causa.getMessage(),
                "Error de SIGELAB",
                JOptionPane.ERROR_MESSAGE
        );
    }

