    private void actualizarLaboratorios() {

        String sede = obtenerSeleccion(cmbSede);

        actualizandoCombos = true;

        try {

            cmbLaboratorio.removeAllItems();
            laboratoriosCombo.clear();

            if (sede == null) {
                return;
            }

            List<Laboratorio> filtrados =
                    new ArrayList<>();

            for (Laboratorio laboratorio :
                    laboratorios) {

                if (sede.equalsIgnoreCase(
                        limpiar(laboratorio.getUbicacion())
                )) {

                    filtrados.add(laboratorio);
                }
            }

            filtrados.sort(
                    Comparator.comparing(
                            Laboratorio::getNombre,
                            String.CASE_INSENSITIVE_ORDER
                    )
            );

            for (Laboratorio laboratorio :
                    filtrados) {

                String nombre =
                        limpiar(laboratorio.getNombre());

                if (nombre.isEmpty()) {
                    continue;
                }

                String etiqueta = nombre;

                /*
                 * Si dos laboratorios tienen el mismo
                 * nombre, se diferencia por código.
                 */

                if (laboratoriosCombo.containsKey(
                        etiqueta
                )) {

                    etiqueta = nombre + " ("
                            + laboratorio.getCodigo()
                            + ")";
                }

                laboratoriosCombo.put(
                        etiqueta,
                        laboratorio
                );

                cmbLaboratorio.addItem(etiqueta);
            }

            if (cmbLaboratorio.getItemCount() > 0) {
                cmbLaboratorio.setSelectedIndex(0);
            }

        } finally {

            actualizandoCombos = false;
        }

        cargarEquiposDelLaboratorio();
    }

    private Laboratorio obtenerLaboratorioSeleccionado() {

        String nombre =
                obtenerSeleccion(cmbLaboratorio);

        if (nombre == null) {
            return null;
        }

        return laboratoriosCombo.get(nombre);
    }

    // ============================================
    // EQUIPOS REALES DEL LABORATORIO
    // ============================================

    private void cargarEquiposDelLaboratorio() {

        Laboratorio laboratorio =
                obtenerLaboratorioSeleccionado();

        catalogo.clear();
        modeloDisponibles.setRowCount(0);

        if (laboratorio == null) {

            cargarCategorias();
            return;
        }

        int idLaboratorio =
                laboratorio.getIdLaboratorio();

        btnAgregarEquipo.setEnabled(false);

        SwingWorker<List<Equipo>, Void> worker =
                new SwingWorker<>() {

                    @Override
                    protected List<Equipo> doInBackground()
                            throws Exception {

                        return equipoRepository
                                .listarPorLaboratorio(
                                        idLaboratorio
                                );
                    }

                    @Override
                    protected void done() {

                        btnAgregarEquipo.setEnabled(true);

                        try {

                            List<Equipo> equipos = get();

                            /*
                             * Ignorar resultados si el
                             * usuario cambió de laboratorio
                             * mientras se consultaba SQL.
                             */

                            Laboratorio actual =
                                    obtenerLaboratorioSeleccionado();

                            if (actual == null
                                    || actual.getIdLaboratorio()
                                    != idLaboratorio) {

                                return;
                            }

                            catalogo.clear();

                            for (Equipo equipo : equipos) {

                                if (equipo.getEstado()
                                        != EstadoEquipo.DISPONIBLE) {

                                    continue;
                                }

                                Producto producto =
                                        productos.get(
                                                equipo.getIdProducto()
                                        );

                                if (producto == null) {
                                    continue;
                                }

                                if (producto.getEstado() == null
                                        || !"ACTIVO".equals(
                                        producto.getEstado().name()
                                )) {

                                    continue;
                                }

                                int idCategoria =
                                        producto.getIdTipoEquipo();

                                String categoria =
                                        nombresCategorias.getOrDefault(
                                                idCategoria,
                                                "Categoría "
                                                        + idCategoria
                                        );

                                catalogo.add(
                                        new EquipoVista(
                                                equipo,
                                                producto,
                                                laboratorio,
                                                categoria
                                        )
                                );
                            }

                            cargarCategorias();
                            filtrarEquipos();

                        } catch (Exception ex) {

                            mostrarError(
                                    "No fue posible consultar "
                                            + "los equipos del laboratorio.",
                                    ex
                            );
                        }
                    }
                };

        worker.execute();
    }

    private void cargarCategorias() {

        actualizandoCombos = true;

        try {

            cmbCategoria.removeAllItems();
            categoriasCombo.clear();

            cmbCategoria.addItem("TODAS");

            Map<String, Integer> ordenadas =
                    new TreeMap<>(
                            String.CASE_INSENSITIVE_ORDER
                    );

            for (EquipoVista equipo : catalogo) {

                ordenadas.put(
                        equipo.categoria,
                        equipo.idTipoEquipo
                );
            }

            for (Map.Entry<String, Integer> entry :
                    ordenadas.entrySet()) {

                String etiqueta = entry.getKey();

                if (categoriasCombo.containsKey(
                        etiqueta
                )) {

                    etiqueta += " ("
                            + entry.getValue()
                            + ")";
                }

                categoriasCombo.put(
                        etiqueta,
                        entry.getValue()
                );

                cmbCategoria.addItem(etiqueta);
            }

            cmbCategoria.setSelectedIndex(0);

        } finally {

            actualizandoCombos = false;
        }
    }

    // ============================================
    // FILTRAR EQUIPOS
    // ============================================

    private void filtrarEquipos() {

        modeloDisponibles.setRowCount(0);

        Laboratorio laboratorio =
                obtenerLaboratorioSeleccionado();

        if (laboratorio == null) {
            return;
        }

        String categoria =
                obtenerSeleccion(cmbCategoria);

        Integer idCategoria =
                categoriasCombo.get(categoria);

        String texto = "";

        if (txtBuscarEquipo != null) {

            texto = limpiar(
                    txtBuscarEquipo.getText()
            ).toLowerCase();
        }

        for (EquipoVista equipo : catalogo) {

            if (agregados.containsKey(
                    equipo.idEquipo
            )) {
                continue;
            }

            if (idCategoria != null
                    && equipo.idTipoEquipo
                    != idCategoria) {

                continue;
            }

            if (!texto.isEmpty()
                    && !coincideBusqueda(
                    equipo,
                    texto
            )) {

                continue;
            }

            modeloDisponibles.addRow(
                    new Object[]{
                            false,
                            equipo.codigo,
                            equipo.nombre,
                            equipo.categoria,
                            equipo.laboratorio,
                            equipo.estado
                    }
            );
        }
    }

    private boolean coincideBusqueda(
            EquipoVista equipo,
            String texto
    ) {

        String filtro = texto.toLowerCase();

        return limpiar(equipo.codigo)
                .toLowerCase().contains(filtro)

                || limpiar(equipo.nombre)
                .toLowerCase().contains(filtro)

                || limpiar(equipo.categoria)
                .toLowerCase().contains(filtro);
    }

    // ============================================
    // BUSCAR POR CÓDIGO O NOMBRE
    // ============================================

    private void buscarEquipos() {

        if (obtenerLaboratorioSeleccionado()
                == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Primero selecciona una sede "
                            + "y un laboratorio.",
                    "Buscar equipos",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        JDialog dialogo = new JDialog(
                SwingUtilities.getWindowAncestor(this),
                "Buscar equipo por código o nombre",
                Dialog.ModalityType.APPLICATION_MODAL
        );

        dialogo.setLayout(new BorderLayout(10, 10));

        JPanel panelBusqueda =
                new JPanel(new BorderLayout(8, 8));

        JTextField txtBusqueda =
                new JTextField();

        JButton btnBuscar =
                new JButton("Buscar");

        panelBusqueda.add(
                new JLabel("Código o nombre:"),
                BorderLayout.WEST
        );

        panelBusqueda.add(
                txtBusqueda,
                BorderLayout.CENTER
        );

        panelBusqueda.add(
                btnBuscar,
                BorderLayout.EAST
        );

        DefaultTableModel modeloBusqueda =
                new DefaultTableModel(
                        new Object[]{
                                "Código",
                                "Equipo",
                                "Categoría",
                                "Estado"
                        },
                        0
                ) {

                    @Override
                    public boolean isCellEditable(
                            int row,
                            int column
                    ) {
                        return false;
                    }
                };

        JTable tablaBusqueda =
                new JTable(modeloBusqueda);

        tablaBusqueda.setRowHeight(26);

        tablaBusqueda.setSelectionMode(
                ListSelectionModel.MULTIPLE_INTERVAL_SELECTION
        );

        List<EquipoVista> resultados =
                new ArrayList<>();

        Runnable actualizarBusqueda = () -> {

            modeloBusqueda.setRowCount(0);
            resultados.clear();

            String filtro = limpiar(
                    txtBusqueda.getText()
            ).toLowerCase();

            for (EquipoVista equipo : catalogo) {

                if (agregados.containsKey(
                        equipo.idEquipo
                )) {
                    continue;
                }

                if (!coincideBusqueda(
                        equipo,
                        filtro
                )) {
                    continue;
                }

                resultados.add(equipo);

                modeloBusqueda.addRow(
                        new Object[]{
                                equipo.codigo,
                                equipo.nombre,
                                equipo.categoria,
                                equipo.estado
                        }
                );
            }
        };

        btnBuscar.addActionListener(
                e -> actualizarBusqueda.run()
        );

        txtBusqueda.addActionListener(
                e -> actualizarBusqueda.run()
        );

        JButton btnAgregar =
                new JButton("Agregar seleccionados");

        JButton btnCerrar =
                new JButton("Cerrar");

        btnAgregar.addActionListener(e -> {

            int[] filas =
                    tablaBusqueda.getSelectedRows();

            if (filas.length == 0) {

                JOptionPane.showMessageDialog(
                        dialogo,
                        "Selecciona al menos un equipo."
                );

                return;
            }

            for (int filaVista : filas) {

                int fila =
                        tablaBusqueda.convertRowIndexToModel(
                                filaVista
                        );

                if (fila >= 0
                        && fila < resultados.size()) {

                    EquipoVista equipo =
                            resultados.get(fila);

                    agregados.put(
                            equipo.idEquipo,
                            equipo
                    );
                }
            }

            actualizarTablaAgregados();
            filtrarEquipos();
            actualizarBusqueda.run();

            JOptionPane.showMessageDialog(
                    dialogo,
                    "Equipos agregados correctamente."
            );
        });

        btnCerrar.addActionListener(
                e -> dialogo.dispose()
        );

        JPanel botones =
                new JPanel(new FlowLayout(
                        FlowLayout.RIGHT
                ));

        botones.add(btnAgregar);
        botones.add(btnCerrar);

        JPanel contenido =
                new JPanel(new BorderLayout(10, 10));

        contenido.setBorder(
                BorderFactory.createEmptyBorder(
                        12, 12, 12, 12
                )
        );

        contenido.add(
                panelBusqueda,
                BorderLayout.NORTH
        );

        contenido.add(
                new JScrollPane(tablaBusqueda),
                BorderLayout.CENTER
        );

        contenido.add(
                botones,
                BorderLayout.SOUTH
        );

        dialogo.add(
                contenido,
                BorderLayout.CENTER
        );

        actualizarBusqueda.run();

        dialogo.setSize(760, 460);
        dialogo.setLocationRelativeTo(this);
        dialogo.setVisible(true);
    }

    // ============================================
    // AGREGAR EQUIPOS
    // ============================================

    private void agregarEquipos() {

        List<String> codigos =
                new ArrayList<>();

        for (int fila = 0;
             fila < modeloDisponibles.getRowCount();
             fila++) {

            if (Boolean.TRUE.equals(
                    modeloDisponibles.getValueAt(
                            fila,
                            0
                    )
            )) {

                codigos.add(
                        Objects.toString(
                                modeloDisponibles.getValueAt(
                                        fila,
                                        1
                                ),
                                ""
                        )
                );
            }
        }

        if (codigos.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Marca los equipos que deseas agregar.",
                    "Agregar equipos",
                    JOptionPane.INFORMATION_MESSAGE
            );

            return;
        }

        for (EquipoVista equipo : catalogo) {

            if (codigos.contains(equipo.codigo)) {

                agregados.put(
                        equipo.idEquipo,
                        equipo
                );
            }
        }

        actualizarTablaAgregados();
        filtrarEquipos();
    }

    // ============================================
    // QUITAR EQUIPO
    // ============================================

    private void quitarEquipo() {

        int filaVista =
                tblEquiposAgregados.getSelectedRow();

        if (filaVista < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecciona el equipo que deseas quitar."
            );

            return;
        }

        int fila =
                tblEquiposAgregados
                        .convertRowIndexToModel(
                                filaVista
                        );

        String codigo =
                Objects.toString(
                        modeloAgregados.getValueAt(
                                fila,
                                0
                        ),
                        ""
                );

        Integer idEliminar = null;

        for (EquipoVista equipo :
                agregados.values()) {

            if (codigo.equals(equipo.codigo)) {

                idEliminar = equipo.idEquipo;
                break;
            }
        }

        if (idEliminar != null) {
            agregados.remove(idEliminar);
        }

        actualizarTablaAgregados();
        filtrarEquipos();
    }

    private void actualizarTablaAgregados() {

        modeloAgregados.setRowCount(0);

        for (EquipoVista equipo :
                agregados.values()) {

            modeloAgregados.addRow(
                    new Object[]{
                            equipo.codigo,
                            equipo.nombre,
                            equipo.categoria,
                            equipo.laboratorio
                    }
            );
        }

        actualizarTotal();
    }

    private void actualizarTotal() {

        if (lblTotalEquipos != null) {

            lblTotalEquipos.setText(
                    "Total de equipos: "
                            + agregados.size()
            );
        }
    }

